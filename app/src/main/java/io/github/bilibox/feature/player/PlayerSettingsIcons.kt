@Composable
internal fun PlayerSettingsGlyph(
    icon: PlayerSettingsIcon,
    tint: Color,
    modifier: Modifier = Modifier,
    strokeWidth: Float = 0f,
) {
    val spec = remember(icon) { GlyphSpecs.getValue(icon) }
    val parsed = remember(spec) {
        spec.paths.map { glyph ->
            PathParser().parsePathString(glyph.data).toPath().apply {
                if (glyph.evenOdd) fillType = PathFillType.EvenOdd
            }
        }
    }
    if (icon == PlayerSettingsIcon.DANMAKU) {
        Canvas(modifier) { drawDanmakuGlyph(tint, spec) }
        return
    }
    Box(modifier, contentAlignment = Alignment.Center) {
        Canvas(Modifier.matchParentSize()) {
            val scaleFactor = min(size.width / spec.width, size.height / spec.height)
            val dx = (size.width - spec.width * scaleFactor) / 2f - spec.left * scaleFactor
            val dy = (size.height - spec.height * scaleFactor) / 2f - spec.top * scaleFactor
            withTransform({ translate(dx, dy) }) {
                scale(scaleFactor, scaleFactor, pivot = Offset.Zero) {
                    spec.paths.forEachIndexed { index, glyph ->
                        val path = parsed[index]
                        if (glyph.fill) drawPath(path, tint)
                        val width = glyph.stroke ?: strokeWidth.takeIf { glyph.fill } ?: 0f
                        if (width > 0f) {
                            drawPath(
                                path,
                                tint,
                                style = Stroke(width, cap = StrokeCap.Round, join = StrokeJoin.Round),
                            )
                        }
                    }
                }
            }
        }
    }
}

